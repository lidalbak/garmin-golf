#!/usr/bin/env python3
"""Package source-derived course headers and one lazily loaded resource per hole."""
import json
from pathlib import Path
from xml.sax.saxutils import escape
from map_scene import scene_for
from map_layout import generate as generate_layout

ROOT = Path(__file__).resolve().parents[1]

def mc(value):
    if value is None: return "null"
    if isinstance(value, str): return json.dumps(value, ensure_ascii=False)
    if isinstance(value, float): return repr(value) + "d"
    if isinstance(value, int): return str(value)
    if isinstance(value, list): return "[" + ",".join(map(mc, value)) + "]"
    if isinstance(value, dict): return "{" + ",".join(mc(k)+"=>"+mc(v) for k,v in value.items()) + "}"
    raise ValueError(type(value))

def main():
    generate_layout()
    data=json.loads((ROOT/"data/courses.json").read_text())
    directory=ROOT/"resources/courses"
    directory.mkdir(parents=True,exist_ok=True)
    headers=[]; refs=[]; xml=[]
    for c in data["courses"]:
        holes=[]; ids=[]
        assert len(c["holes"])<=36
        for h in c["holes"]:
            assert 3<=h["par"]<=6 and len(h["green"])>=3
            name=c["id"]+str(h["number"])
            assert name.replace("_","").isalnum()
            geometry={k:h[k] for k in ("green","path")}
            geometry["hazards"]=[{"type":z["type"],"points":z["points"]} for z in h["hazards"]]
            geometry["scene"]=scene_for(c,h)
            (directory/(name+".json")).write_text(json.dumps(geometry,separators=(",",":")))
            xml.append(f'<jsonData id="{name}" filename="{name}.json"/>')
            ids.append("Rez.JsonData."+name)
            holes.append({k:h[k] for k in ("number","par","strokeIndex","tee","center")})
        headers.append({"id":c["id"],"name":"Bogstad" if c["id"]=="bogstad" else "Bærum GK","note":"OSM · ikke feltverifisert","holes":holes})
        refs.append("["+",".join(ids)+"]")
    (directory/"courses.xml").write_text("<jsonDataResources>"+"".join(xml)+"</jsonDataResources>")
    style=json.loads((ROOT/'data/map-style.json').read_text())
    colors={k:style[k] for k in ('grass','rough','forest','water','fairway','tee','bunker','green')}
    code='// Generated from data/map-style.json.\nmodule MapStyle {\n function colors() { return {'+','.join(mc(k)+'=>0x'+v for k,v in colors.items())+'}; }\n'
    for k in ('background','treeShadow'):
        code+=' const '+k+' = 0x'+style[k]+';\n'
    for k in ('treeCanopy','treeHighlight'):
        code+=' const '+k+' = ['+','.join('0x'+v for v in style[k])+'];\n'
    code+='}\n'
    (ROOT/'source/MapStyle.mc').write_text(code)
    text='// Generated by scripts/generate_courses.py from data/courses.json.\nimport Toybox.WatchUi;\nmodule Courses {\n'
    text+=' function catalog() { return '+mc(headers)+'; }\n'
    text+=' function geometry(course,hole) { var ids=['+",".join(refs)+']; return WatchUi.loadResource(ids[course][hole]); }\n}\n'
    (ROOT/"source/Courses.mc").write_text(text)
    print(f'Packaged {sum(len(c["holes"]) for c in data["courses"])} holes; geometry loaded one hole at a time.')

if __name__=="__main__": main()
